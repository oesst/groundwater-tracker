// Nordrhein-Westfalen — OpenHygrisC (LANUK open data).
//
// NRW's ELWAS-WEB portal has NO public/stable API: it is a JSF (Jakarta Faces)
// web form whose per-station replay flow breaks on any site change and throttles
// automated clients. We therefore read the state's bulk open-data release instead:
//
//   OpenHygrisC "Grundwasserstaende" (Landesamt fuer Natur, Umwelt und Klima NRW)
//   https://www.opengeodata.nrw.de/produkte/umwelt_klima/wasser/grundwasser/hygrisc/
//
// That export is published as EPSG:25832 CSV zips. It is NOT a live feed: each
// station carries its own "latest available" reading, and those dates range from
// days to a couple of years old. We surface that honestly — every station keeps
// its true measurement date (measured_at), and the frontend flags readings that
// are no longer current (see `stale`).
//
// Snapshot file: data/nw.levels.json — regenerated by
// scripts/build-nw-openhygrisc.js (runs in CI, which has open internet). Each
// entry: { id, name, lat, lon, nhn, flur, pct, measured_at }.
//   nhn  = water level, m ue. NHN (latest available)
//   flur = Flurabstand, m below ground
//   pct  = empirical percentile of the latest value within that well's own
//          2020..present distribution (drives bar height + colour class)
//
// If the open-data layout ever changes, only the build script needs updating;
// this adapter and the committed snapshot keep the site working meanwhile.

import { readFile } from 'node:fs/promises';

// Readings older than this many days are flagged as no-longer-current.
const STALE_DAYS = 120;

async function loadLevels() {
  try {
    const url = new URL('../data/nw.levels.json', import.meta.url);
    const txt = await readFile(url, 'utf8');
    const arr = JSON.parse(txt);
    return Array.isArray(arr) ? arr : [];
  } catch {
    return [];
  }
}

export default {
  id: 'nw',
  name: 'Nordrhein-Westfalen — OpenHygrisC / LANUK',
  kind: 'state',
  // Not a live feed: the open-data export carries the last released value per well.
  cadence: 'Offene Daten (OpenHygrisC) — letzter verfuegbarer Wert je Messstelle',
  attribution: 'Landesamt fuer Natur, Umwelt und Klima NRW (LANUK), OpenHygrisC',
  license: 'DL-DE Zero 2.0',
  async fetch() {
    const rows = await loadLevels();
    if (!rows.length) {
      throw new Error('nw.levels.json empty or missing — run scripts/build-nw-openhygrisc.js');
    }
    const now = Date.now();
    return rows
      .filter((r) => r && typeof r.nhn === 'number' && r.measured_at)
      .map((r) => {
        const ageDays = (now - Date.parse(r.measured_at)) / 86400000;
        return {
          id: `nw-${r.id}`,
          name: r.name || `GWM ${r.id}`,
          state: 'Nordrhein-Westfalen',
          lat: r.lat,
          lon: r.lon,
          nhn: r.nhn,
          flur: (typeof r.flur === 'number') ? r.flur : null,
          pct: (typeof r.pct === 'number') ? r.pct : null,
          measured_at: r.measured_at + 'T00:00:00',
          // Honest recency flag: many OpenHygrisC values are months/years old.
          stale: Number.isFinite(ageDays) ? ageDays > STALE_DAYS : true,
        };
      });
  },
};
